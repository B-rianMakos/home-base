"""Writes the licence of every Python package shipped in the app (FR-3).

    python tools/licences.py THIRD-PARTY-LICENSES.md
"""

from __future__ import annotations

import sys
from importlib import metadata
from pathlib import Path

# The runtime dependencies in pyproject.toml, plus everything they pull in.
ROOTS = ["cryptography", "fastapi", "google-api-python-client", "google-auth", "google-auth-oauthlib", "httpx",
         "keyring", "PySide6-Essentials", "python-dateutil", "tzdata", "uvicorn", "zeroconf"]


def _name(req: str) -> str:
    for sep in (" ", ";", "<", ">", "=", "!", "~", "[", "("):
        req = req.split(sep, 1)[0]
    return req


def runtime_closure() -> list[metadata.Distribution]:
    seen: dict[str, metadata.Distribution] = {}
    todo = list(ROOTS)
    while todo:
        name = todo.pop()
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        key = dist.metadata["Name"].lower().replace("_", "-")
        if key in seen:
            continue
        seen[key] = dist
        for req in dist.requires or []:
            if "extra ==" not in req:
                todo.append(_name(req))
    return sorted(seen.values(), key=lambda d: d.metadata["Name"].lower())


def licence_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expr = meta.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(classifiers)
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:80] if text else "see package"


def main() -> None:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "THIRD-PARTY-LICENSES.md")
    lines = ["# Third-party licences", "", "Python packages shipped inside Home Base, with their licences.",
             "Generated by `tools/licences.py`.", "", "| Package | Version | Licence |", "|---|---|---|"]
    for dist in runtime_closure():
        lines.append(f"| {dist.metadata['Name']} | {dist.version} | {licence_of(dist)} |")
    lines += ["", "PySide6 (Qt for Python) is used under the LGPL v3. It is shipped as separate, replaceable",
              "libraries in the install folder, as the LGPL allows. Its source is at https://code.qt.io/.",
              "", "## Fonts and icons", "",
              "Bundled in `family_scheduler/app/assets/` (WO-FS-004, IF-4). Both are free.", "",
              "| Asset | Version | Licence | Licence text |", "|---|---|---|---|",
              "| Inter font (Regular, Medium, SemiBold, Bold), https://rsms.me/inter/ | 4.1 | "
              "SIL Open Font License 1.1 | `assets/fonts/OFL.txt` |",
              "| Lucide icons (33 icons), https://lucide.dev/ | 0.460.0 | ISC | `assets/icons/LICENSE-lucide.txt` |",
              "", "The app icon is original to Home Base and drawn in code (`app/icons.py`)."]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
